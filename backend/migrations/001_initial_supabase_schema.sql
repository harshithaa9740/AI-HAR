-- Features:
--  - 100% table and column alignment with local AURAVISION models
--  - Native PostgreSQL types: TIMESTAMPTZ, JSONB, BOOLEAN, BIGINT IDENTITY
--  - Preserves integer IDs via 'GENERATED BY DEFAULT AS IDENTITY' for seamless sync
--  - Strict foreign-key cascades and integrity constraints
--  - GIN indexes for fast JSONB querying (metadata, validation rules)
--  - B-tree composite indexes for timeline queries and step ordering
--  - Automated updated_at trigger management
--  - Comprehensive Row Level Security (RLS) policies
