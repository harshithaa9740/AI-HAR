-- 0. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ============================================================================
-- 1. EXPERIMENT PROTOCOLS (experiments)
-- ============================================================================
CREATE TABLE IF NOT EXISTS experiments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,
    version VARCHAR(50) NOT NULL DEFAULT '1.0',
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

-- Indexes
CREATE INDEX IF NOT EXISTS ix_experiments_name ON experiments (name);
CREATE INDEX IF NOT EXISTS ix_experiments_active ON experiments (is_active);

-- ============================================================================
-- 2. PROTOCOL STEPS (experiment_steps)
-- ============================================================================
CREATE TABLE IF NOT EXISTS experiment_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id BIGINT NOT NULL REFERENCES experiments(id) ON DELETE CASCADE,
    step_number INTEGER NOT NULL,
    step_code VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    expected_action VARCHAR(100) NOT NULL,
    required_objects JSONB NOT NULL DEFAULT '[]'::jsonb,
    confidence_threshold DOUBLE PRECISION NOT NULL DEFAULT 0.70,
    validation_rules JSONB DEFAULT NULL,
    expected_duration_seconds INTEGER DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT uq_step_protocol_number UNIQUE (experiment_id, step_number)
);

-- Indexes
CREATE INDEX IF NOT EXISTS ix_step_experiment_id ON experiment_steps (experiment_id);
CREATE INDEX IF NOT EXISTS ix_step_experiment_number ON experiment_steps (experiment_id, step_number);
CREATE INDEX IF NOT EXISTS ix_step_required_objects_gin ON experiment_steps USING gin (required_objects);

-- ============================================================================
-- 3. EXPERIMENT SESSIONS (experiment_sessions)
-- ============================================================================
CREATE TABLE IF NOT EXISTS experiment_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id BIGINT NOT NULL REFERENCES experiments(id) ON DELETE CASCADE,
    session_uuid VARCHAR(64) NOT NULL UNIQUE DEFAULT gen_random_uuid()::text,
    session_name VARCHAR(255),
    status VARCHAR(50) NOT NULL DEFAULT 'CREATED',
    started_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    current_step_number INTEGER DEFAULT 1,
    current_step_code VARCHAR(50),
    expected_next_step VARCHAR(100),
    operator_label VARCHAR(100) DEFAULT 'Astronaut Specialist',
    notes TEXT,
    recording_path VARCHAR(500),
    stream_enabled BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ DEFAULT clock_timestamp()
);

-- Indexes
CREATE INDEX IF NOT EXISTS ix_experiment_sessions_session_uuid ON experiment_sessions (session_uuid);
CREATE INDEX IF NOT EXISTS ix_experiment_sessions_experiment_id ON experiment_sessions (experiment_id);
CREATE INDEX IF NOT EXISTS ix_session_exp_created ON experiment_sessions (experiment_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_session_status ON experiment_sessions (status);

-- ============================================================================
-- 4. ACTIVITY DETECTIONS (detection_events)
-- ============================================================================
CREATE TABLE IF NOT EXISTS detection_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT REFERENCES experiment_sessions(id) ON DELETE CASCADE,
    protocol_step_id BIGINT REFERENCES experiment_steps(id) ON DELETE SET NULL,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    frame_number INTEGER,
    start_time_ms DOUBLE PRECISION,
    end_time_ms DOUBLE PRECISION,
    entity_type VARCHAR(50) NOT NULL,
    entity_name VARCHAR(100) NOT NULL,
    confidence DOUBLE PRECISION,
    bbox JSONB,
    source VARCHAR(100),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);

-- Indexes
CREATE INDEX IF NOT EXISTS ix_detection_session_time ON detection_events (session_id, timestamp ASC);
CREATE INDEX IF NOT EXISTS ix_detection_step_id ON detection_events (protocol_step_id);
CREATE INDEX IF NOT EXISTS ix_detection_entity ON detection_events (entity_type, entity_name);
CREATE INDEX IF NOT EXISTS ix_detection_timestamp ON detection_events (timestamp);
CREATE INDEX IF NOT EXISTS ix_detection_metadata_gin ON detection_events USING gin (metadata);

-- ============================================================================
-- 5. VALIDATION EVENTS (sequence_events)
-- ============================================================================
CREATE TABLE IF NOT EXISTS sequence_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT REFERENCES experiment_sessions(id) ON DELETE CASCADE,
    protocol_step_id BIGINT REFERENCES experiment_steps(id) ON DELETE SET NULL,
    event_type VARCHAR(50),
    timestamp TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    expected_step_number INTEGER,
    expected_step_code VARCHAR(50),
    observed_step_number INTEGER,
    observed_step_code VARCHAR(50),
    result VARCHAR(50) NOT NULL,
    confidence DOUBLE PRECISION,
    message TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);

-- Indexes
CREATE INDEX IF NOT EXISTS ix_sequence_session_time ON sequence_events (session_id, timestamp ASC);
CREATE INDEX IF NOT EXISTS ix_sequence_step_id ON sequence_events (protocol_step_id);
CREATE INDEX IF NOT EXISTS ix_sequence_result ON sequence_events (result);
CREATE INDEX IF NOT EXISTS ix_sequence_timestamp ON sequence_events (timestamp);
CREATE INDEX IF NOT EXISTS ix_sequence_metadata_gin ON sequence_events USING gin (metadata);

-- ============================================================================
-- 6. ALERT EVENTS (alert_events)
-- ============================================================================
CREATE TABLE IF NOT EXISTS alert_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT REFERENCES experiment_sessions(id) ON DELETE CASCADE,
    validation_event_id BIGINT REFERENCES sequence_events(id) ON DELETE SET NULL,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    alert_type VARCHAR(50) NOT NULL,
    severity VARCHAR(20) NOT NULL DEFAULT 'INFO',
    category VARCHAR(50) NOT NULL DEFAULT 'protocol',
    message TEXT NOT NULL,
    acknowledged BOOLEAN NOT NULL DEFAULT false,
    acknowledged_at TIMESTAMPTZ,
    spoken BOOLEAN NOT NULL DEFAULT false,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);

-- Indexes
CREATE INDEX IF NOT EXISTS ix_alert_session_time ON alert_events (session_id, timestamp ASC);
CREATE INDEX IF NOT EXISTS ix_alert_validation_event ON alert_events (validation_event_id);
CREATE INDEX IF NOT EXISTS ix_alert_severity ON alert_events (severity);
CREATE INDEX IF NOT EXISTS ix_alert_acknowledged ON alert_events (acknowledged);
CREATE INDEX IF NOT EXISTS ix_alert_timestamp ON alert_events (timestamp);
CREATE INDEX IF NOT EXISTS ix_alert_metadata_gin ON alert_events USING gin (metadata);

-- ============================================================================
-- 7. SESSION ARTIFACTS (session_artifacts)
-- ============================================================================
CREATE TABLE IF NOT EXISTS session_artifacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES experiment_sessions(id) ON DELETE CASCADE,
    artifact_type VARCHAR(50) NOT NULL,
    file_path VARCHAR(500) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    file_size_bytes BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);

-- Indexes
CREATE INDEX IF NOT EXISTS ix_session_artifacts_session_id ON session_artifacts (session_id);
CREATE INDEX IF NOT EXISTS ix_artifact_session_type ON session_artifacts (session_id, artifact_type);

-- ============================================================================
-- 8. SYSTEM SETTINGS (system_settings)
-- ============================================================================
CREATE TABLE IF NOT EXISTS system_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key VARCHAR(100) NOT NULL UNIQUE,
    setting_value TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

-- Indexes
CREATE INDEX IF NOT EXISTS ix_system_settings_setting_key ON system_settings (setting_key);

-- ============================================================================
-- 9. SYSTEM EVENTS (system_events)
-- ============================================================================
CREATE TABLE IF NOT EXISTS system_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT REFERENCES experiment_sessions(id) ON DELETE CASCADE,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    event_type VARCHAR(50) NOT NULL,
    severity VARCHAR(20) NOT NULL DEFAULT 'INFO',
    message TEXT NOT NULL,
    component VARCHAR(50),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);

-- Indexes
CREATE INDEX IF NOT EXISTS ix_system_events_session_id ON system_events (session_id);
CREATE INDEX IF NOT EXISTS ix_system_event_time ON system_events (timestamp);
CREATE INDEX IF NOT EXISTS ix_system_events_severity ON system_events (severity);

-- ============================================================================
-- AUTOMATIC TIMESTAMPTZ TRIGGER FOR updated_at
-- ============================================================================
CREATE OR REPLACE FUNCTION set_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = clock_timestamp();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_experiments_updated_at ON experiments;
CREATE TRIGGER trg_experiments_updated_at
BEFORE UPDATE ON experiments
FOR EACH ROW EXECUTE FUNCTION set_updated_at_column();

DROP TRIGGER IF EXISTS trg_sessions_updated_at ON experiment_sessions;
CREATE TRIGGER trg_sessions_updated_at
BEFORE UPDATE ON experiment_sessions
FOR EACH ROW EXECUTE FUNCTION set_updated_at_column();

DROP TRIGGER IF EXISTS trg_system_settings_updated_at ON system_settings;
CREATE TRIGGER trg_system_settings_updated_at
BEFORE UPDATE ON system_settings
FOR EACH ROW EXECUTE FUNCTION set_updated_at_column();

-- ============================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- ============================================================================
-- Strict zero-trust security model:
-- 1. Backend Sync uses 'service_role' (bypasses RLS automatically in Supabase).
-- 2. Authenticated ground operators have read/write access.
-- 3. Anonymous public users only have read access to published active protocols.

ALTER TABLE experiments ENABLE ROW LEVEL SECURITY;
ALTER TABLE experiment_steps ENABLE ROW LEVEL SECURITY;
ALTER TABLE experiment_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE detection_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE sequence_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE alert_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE session_artifacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE system_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE system_events ENABLE ROW LEVEL SECURITY;

